package.path = "os/init/init.d/?.lua;os/?.lua;" .. package.path

local path = require("path")

assert(path.normalize("a/./b/../c") == "a/c")
assert(path.normalize("/../a") == "/a")
assert(path.normalize("") == ".")
assert(path.normalize("/") == "/")
assert(path.join("/", "/root") == "/root")
assert(path.join("a", "b") == "a/b")
assert(path.join("a/", "b") == "a/b")
assert(path.dirname("/a/b/c") == "/a/b")
assert(path.dirname("/") == "/")
assert(path.dirname("file") == ".")
assert(path.basename("/a/b/c.lua") == "c.lua")
assert(path.basename("/") == "/")
assert(path.extname("c.lua") == ".lua")
assert(path.isAbsolute("/tmp"))
assert(not path.isAbsolute("tmp"))
assert(path.exists("os/System.lua"))
assert(not path.exists("does-not-exist.lua"))

local saved_arg = arg
arg = {
    "-root=/img/root.bin",
    "drv_root=/kern/builts",
    "mem=dynamic",
    "verbose"
}

local base = dofile("os/init/init.d/os.lua")
arg = saved_arg

assert(package.loaded["gothos"] == base)
assert(base:getName() == "GothRTOS")
assert(base:getVersion() == "0.0-indev")
assert(base:getBuild() == "indev")
assert(base:getRoot() == "/")
assert(base:getOption("root") == "/img/root.bin")
assert(base:getOption("drv_root") == "/kern/builts")
assert(base:getOption("mem") == "dynamic")
assert(base:getOption("verbose") == true)
assert(base:getOption("missing") == nil)
assert(base:getMemoryPolicy() == "dynamic")
assert(base:getSymbolPath() == "/kern.symbols")
assert(#base:getArguments() == 4)

assert(base:setRoot("tmp") == true)
assert(base:getRoot() == "/tmp")
assert(base:setRoot("") == false)

assert(base:isHalted() == false)
assert(base:halt("halted") == true)
assert(base:isHalted() == true)
assert(base:getError() == "halted")
assert(base:reboot() == true)
assert(base:isHalted() == false)
assert(base:getError() == nil)

local mounts = require("kernel_mounts")
mounts:reset()
assert(mounts:mount("/img/root.bin", "/", "rootfs") == true)
assert(mounts:isMounted("/"))
assert(mounts:mount("/kern.builts", "/drivers", "hostfs") == true)
assert(mounts:find("/drivers/input").target == "/drivers")
assert(mounts:find("/etc/passwd").target == "/")
assert(mounts:find(nil) == nil)
assert(mounts:declare("/img/data.bin", "/data", "datafs") == true)
assert(mounts:mountAll() == true)
assert(mounts:isMounted("/data"))
assert(mounts:unmount("/data") == true)
assert(not mounts:isMounted("/data"))
assert(mounts:unmount("/data") == false)
assert(mounts:mount("/other", "/", "rootfs") == false)
assert(#mounts:list() == 2)

mounts:reset()
assert(mounts:declare("/a", "/same", "x") == true)
assert(mounts:declare("/b", "/same", "x") == true)
assert(mounts:mountAll() == false)
mounts:reset()

local kernelfs = require("kernelmode")
local missing, missing_error = kernelfs:readFile("/kern/init.d/init.lua")
assert(missing == nil)
assert(missing_error ~= nil)
assert(kernelfs:mountAll() == true)
assert(kernelfs:isMounted() == true)
assert(kernelfs:getMountPoint() == "/kern")
assert(#kernelfs:list() >= 2)

local system_source = assert(kernelfs:readFile("/kern/init.d/sys/System.lua"))
assert(system_source:find("GothRTOS system state module", 1, true) ~= nil)
assert(kernelfs:exists("/kern/init.d/init.lua") == true)
assert(kernelfs:exists("/kern/does-not-exist.lua") == false)
local write_handle = kernelfs:open("/kern/init.d/init.lua", "w")
assert(write_handle == nil)
assert(kernelfs:resolve("/kern/init.d/sys/System.lua") ~= nil)

local sh = require("sh")
assert(sh:setCwd("/tmp") == true)
assert(sh:getCwd() == "/tmp")
assert(sh:setCwd("/tmp/../var") == true)
assert(sh:getCwd() == "/var")
assert(sh:setCwd("") == false)
local ok, result = sh:execute("return 1 + 1")
assert(ok == true)
assert(result == 2)
local bad_ok, bad_error = sh:execute("error('boom')")
assert(bad_ok == false)
assert(tostring(bad_error):find("boom", 1, true) ~= nil)
local syntax_ok = sh:execute("this is not lua")
assert(syntax_ok == false)
assert(sh:run("/nonexistent-goth-directory") == true)
assert(#sh.history == 3)

local users = require("userapi")
assert(users:currentUser().name == "root")
assert(users:isRoot() == true)
assert(users:getUid() == 0)
assert(users:getGid() == 0)
assert(users:setUser("nobody") == false)
assert(users:addUser("goth", 1000, 1000, "/home/goth") == true)
assert(users:addUser("goth", 1000, 1000) == false)
assert(users:setUser("goth") == true)
assert(users:isRoot() == false)
assert(users:getEnv("USER") == "goth")
assert(users:setEnv("FOO", "bar") == true)
assert(users:getEnv("FOO") == "bar")
assert(users:setEnv("FOO", nil) == true)
assert(users:getEnv("FOO") == nil)
local task_id = assert(users:spawn("sh", { "/root" }))
assert(type(task_id) == "number")
assert(users:getTask(task_id).program == "sh")
assert(#users:listTasks() == 1)
assert(users:kill(task_id) == true)
assert(users:reap(task_id) == true)
assert(users:getTask(task_id) == nil)
assert(users:reap(task_id) == false)
assert(users:removeUser("root") == false)

local System = dofile("os/System.lua")
assert(System:getVersion() == "0.0-indev")
assert(System:isBooted() == false)
assert(System:boot() == true)
assert(System:isBooted() == true)
assert(System:halt("done") == true)
assert(System:isBooted() == false)
assert(System:getError() == "done")


#ifndef GOTHRTOS_SYSCALL_H
#define GOTHRTOS_SYSCALL_H

#include "gothrtos/kernel.h"

typedef enum {
    GOTH_SYSCALL_TASK_YIELD = 1U,
    GOTH_SYSCALL_TASK_SLEEP,
    GOTH_SYSCALL_TASK_EXIT,
    GOTH_SYSCALL_TASK_SELF,
    GOTH_SYSCALL_KERNEL_TICKS,
    GOTH_SYSCALL_KERNEL_TASK_COUNT,
    GOTH_SYSCALL_KERNEL_GET_SCHED,
    GOTH_SYSCALL_KERNEL_SET_SCHED,
    GOTH_SYSCALL_KERNEL_GET_QUANTUM,
    GOTH_SYSCALL_KERNEL_SET_QUANTUM,
    GOTH_SYSCALL_ENDPOINT_SEND,
    GOTH_SYSCALL_ENDPOINT_RECEIVE,
    GOTH_SYSCALL_ENDPOINT_POLL,
    GOTH_SYSCALL_KLOG_COUNT,
    GOTH_SYSCALL_KLOG_LINE,
    GOTH_SYSCALL_MEM_REGIONS,
    GOTH_SYSCALL_MEM_VIOLATIONS,
    GOTH_SYSCALL_MEM_CHECK,
    GOTH_SYSCALL_VFS_OPEN,
    GOTH_SYSCALL_VFS_CLOSE,
    GOTH_SYSCALL_VFS_READ,
    GOTH_SYSCALL_VFS_WRITE,
    GOTH_SYSCALL_VFS_SEEK,
    GOTH_SYSCALL_VFS_TRUNCATE,
    GOTH_SYSCALL_VFS_STAT,
    GOTH_SYSCALL_VFS_MKDIR,
    GOTH_SYSCALL_VFS_UNLINK,
    GOTH_SYSCALL_VFS_READDIR,
    GOTH_SYSCALL_VFS_USAGE
} goth_syscall_number_t;

typedef struct {
    uint32_t number;
    uintptr_t arguments[4];
} goth_syscall_request_t;

typedef struct {
    goth_status_t status;
    uint64_t value;
} goth_syscall_result_t;

goth_syscall_result_t goth_syscall_dispatch(
    const goth_syscall_request_t *request);

#endif
